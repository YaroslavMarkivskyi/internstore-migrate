def _req(method: str, url: str, token: str | None = None, body: dict | None = None):
    data = json.dumps(body).encode() if body is not None else None
    r = urllib.request.Request(url, data=data, method=method)
    r.add_header("Content-Type", "application/json")
    if token:
        r.add_header("Authorization", f"Bearer {token}")
    try:
        with urllib.request.urlopen(r, context=_CTX) as resp:
            raw = resp.read()
            return resp.status, (json.loads(raw) if raw else None)
    except urllib.error.HTTPError as exc:
        raw = exc.read()
        try:
            return exc.code, json.loads(raw)
        except Exception:
            return exc.code, {"raw": raw.decode(errors="replace")}


def login() -> str:
    status, body = _req(
        "POST",
        f"{EMULATOR}/identitytoolkit.googleapis.com/v1/accounts:signInWithPassword?key=fake-api-key",
        body={"email": ADMIN_EMAIL, "password": ADMIN_PASSWORD, "returnSecureToken": True},
    )
    if status != 200 or not isinstance(body, dict) or "idToken" not in body:
        sys.exit(f"admin login failed ({status}): {body}")
    return body["idToken"]


def wipe(token: str) -> None:
    _, products = _req("GET", f"{GATEWAY}/api/catalog/products")
    for p in products or []:
        code, _ = _req("DELETE", f"{GATEWAY}/api/catalog/products/{p['id']}", token)
        print(f"product  - {p['name']}  ({code})")
    _, cats = _req("GET", f"{GATEWAY}/api/catalog/categories")
    for c in cats or []:
        code, _ = _req(
            "DELETE", f"{GATEWAY}/api/catalog/categories/{c['id']}", token,
            {"deletion_mode": "unpublish_and_delete"},
        )
        print(f"category - {c['name']}  ({code})")


def main() -> None:
    token = login()
    if WIPE:
        print("--- wiping existing catalogue ---")
        wipe(token)

    _, existing = _req("GET", f"{GATEWAY}/api/catalog/categories")
    cat_ids = {c["name"]: c["id"] for c in (existing or [])}
    for name in CATALOGUE:
        if name in cat_ids:
            continue
        status, body = _req("POST", f"{GATEWAY}/api/catalog/categories", token, {"name": name})
        if status == 201:
            cat_ids[name] = body["id"]
            print(f"category + {name}")
        else:
            print(f"category ! {name}: {status} {body}")

    _, existing_products = _req("GET", f"{GATEWAY}/api/catalog/products")
    have = {p["name"] for p in (existing_products or [])}
    product_ids = {p["name"]: p["id"] for p in (existing_products or [])}
    created = 0
    for cat, items in CATALOGUE.items():
        cid = cat_ids.get(cat)
        if not cid:
            continue
        for name, price, desc, tmin, tmax in items:
            if name in have:
                continue
            payload = {"name": name, "price": price, "category_id": cid, "description": desc}
            if tmin is not None:
                payload["min_temperature"] = tmin
            if tmax is not None:
                payload["max_temperature"] = tmax
            status, body = _req("POST", f"{GATEWAY}/api/catalog/products", token, payload)
            if status == 201:
                product_ids[name] = body["id"]
                created += 1
                print(f"product  + {name}  (₴{price})")
            else:
                print(f"product  ! {name}: {status} {body}")
    print(f"\n{created} product(s) created, {len(product_ids)} total")

    # inventory: one cold room, stock for most products
    _, stocks = _req("GET", f"{GATEWAY}/api/inventory/stocks", token)
    stock_id = next((s["id"] for s in (stocks or []) if s["name"] == STOCK_NAME), None)
    if not stock_id:
        status, body = _req(
            "POST", f"{GATEWAY}/api/inventory/stocks", token,
            {"name": STOCK_NAME, "temperature": 4.0, "humidity": 80.0},
        )
        if status != 201:
            sys.exit(f"could not create stock room: {status} {body}")
        stock_id = body["id"]
        print(f"\nstock room + {STOCK_NAME}")

    _, items = _req("GET", f"{GATEWAY}/api/inventory/stocks/{stock_id}/items", token)
    stocked = {i["product_id"] for i in (items or [])}
    out_of_stock = {"Ікра форелі", "Мідії на канаті"}
    low_stock = {"Моцарела з молока буйволиці": 3, "Філе сібаса": 2}

    added = 0
    for name, pid in product_ids.items():
        if pid in stocked or name in out_of_stock:
            continue
        status, _ = _req(
            "POST", f"{GATEWAY}/api/inventory/stocks/{stock_id}/items", token,
            {"product_id": pid, "quantity": low_stock.get(name, 120)},
        )
        if status == 201:
            added += 1
    print(f"{added} product(s) stocked in {STOCK_NAME} "
          f"(out of stock on purpose: {', '.join(sorted(out_of_stock))})")

    print("\nNext: rebuild the embedding index —")
    print("  PRUNE=1 docker compose exec -T ai-assistant /app/.venv/bin/python - "
          "< scripts/backfill-embeddings.py")
